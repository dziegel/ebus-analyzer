#!/usr/bin/env node
// Bundles the TypeSpec compiler worker (web/dist/tsp-worker.js) with esbuild.
// Needs `npm install`. Without the packages, the build is skipped and the app
// runs without TypeSpec support (set REQUIRE_TSP=1 to fail instead).

import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const required = process.env.REQUIRE_TSP === '1';

function skip(reason) {
  const msg = `[build-tsp] TypeSpec worker not built: ${reason}`;
  if (required) {
    console.error(msg);
    process.exit(1);
  }
  console.warn(`${msg} (run "npm install" to enable TypeSpec support)`);
  process.exit(0);
}

let esbuild;
let libs;
try {
  esbuild = await import('esbuild');
} catch {
  skip('esbuild is not installed');
}
try {
  const { collectLibraries } = await import('./tsp-libs.mjs');
  libs = collectLibraries();
} catch (err) {
  skip(err.message);
}

// Generated module: library files and static imports of their JS modules.
const lines = ['// generated by scripts/build-tsp.mjs - do not edit'];
const entries = [];
let n = 0;
for (const lib of libs) {
  const js = lib.js.map(({ rel, abs }) => {
    const id = `m${n++}`;
    lines.push(`import * as ${id} from ${JSON.stringify(pathToFileURL(abs).pathname)};`);
    return `${JSON.stringify(rel)}: () => Promise.resolve(${id})`;
  });
  entries.push(`  { name: ${JSON.stringify(lib.name)}, files: ${JSON.stringify(lib.files)}, js: { ${js.join(', ')} } }`);
}
lines.push(`export const libraries = [\n${entries.join(',\n')}\n];`);
const generated = join(root, 'src/tsp/tsp-libs.generated.js');
writeFileSync(generated, `${lines.join('\n')}\n`);
for (const lib of libs) {
  console.log(`[build-tsp] ${lib.name}: ${Object.keys(lib.files).length} files, js: ${lib.js.map((j) => j.rel).join(', ')}`);
}

// Node built-ins that may be imported by the compiler or the emitter but are
// not needed in the browser: replaced by a stub that fails only when used.
const NODE_BUILTINS = /^(node:)?(fs|fs\/promises|url|os|crypto|util|module|child_process|net|readline|stream|events|worker_threads|perf_hooks|assert|tty|v8|vm|zlib|http|https|buffer)$/;
const nodeShim = {
  name: 'node-shim',
  setup(build) {
    build.onResolve({ filter: NODE_BUILTINS }, (args) => ({ path: args.path, namespace: 'node-shim' }));
    build.onLoad({ filter: /.*/, namespace: 'node-shim' }, (args) => ({
      contents: `const fail = (name) => () => { throw new Error(${JSON.stringify(args.path)} + "." + String(name) + " is not available in the browser"); };
module.exports = new Proxy({}, { get: (_, name) => name === "__esModule" ? false : fail(name) });`,
      loader: 'js',
    }));
  },
};

mkdirSync(join(root, 'web/dist'), { recursive: true });
const result = await esbuild.build({
  entryPoints: [join(root, 'src/tsp/worker.ts')],
  outfile: join(root, 'web/dist/tsp-worker.js'),
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  sourcemap: true,
  metafile: true,
  conditions: ['browser', 'import', 'default'],
  mainFields: ['browser', 'module', 'main'],
  alias: { path: 'path-browserify', 'node:path': 'path-browserify' },
  define: { 'process.env.NODE_ENV': '"production"' },
  banner: {
    js: 'globalThis.process ??= { env: {}, argv: [], versions: {}, platform: "browser", cwd: () => "/", emitWarning() {}, nextTick: (f, ...a) => queueMicrotask(() => f(...a)) };',
  },
  plugins: [nodeShim],
  logLevel: 'warning',
});
const shimmed = Object.keys(result.metafile.inputs).filter((p) => p.startsWith('node-shim:'));
const size = Object.values(result.metafile.outputs).reduce((s, o) => s + o.bytes, 0);
console.log(`[build-tsp] web/dist/tsp-worker.js: ${(size / 1024 / 1024).toFixed(1)} MB (incl. source map)${shimmed.length ? `, stubbed: ${shimmed.join(', ')}` : ''}`);
