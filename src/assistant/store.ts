// Saved definition drafts (ASS-7), persisted in IndexedDB by the app.

import { parseDefinitionFile } from '../defs/definitions.ts';
import type { LoadedFile } from '../defs/repository.ts';
import { writeTypeSpec } from '../tsp/writer.ts';
import { draftDefinition, draftsCsv, type Draft } from './draft.ts';

export const DRAFTS_PATH = 'assistant:drafts.csv';
/** First line of TypeSpec files written from drafts; such files are replaced without asking. */
export const TSP_MARKER = '// Generated by the EBus Analyzer definition assistant from the saved drafts.';
/**
 * Path of the TypeSpec file for drafts of a target address and circuit. The
 * emitter names the CSV after it and leaves out ZZ and circuit columns that
 * the file name provides, so the name has to be one ebusd can parse:
 * "ZZ.circuit" only for circuits of up to 5 characters (the ident part of an
 * ebusd file name), broadcasts without ZZ like ebusd-configuration.
 */
export function draftTspPath(zz: number, circuit: string): string {
  const c = circuit.toLowerCase();
  if (zz === 0xfe) return `assistant/${c}.tsp`;
  const z = zz.toString(16).padStart(2, '0');
  return c.length <= 5 ? `assistant/${z}.${c}.tsp` : `assistant/${z}.drafts.tsp`;
}

export class DraftStore {
  #drafts = new Map<string, Draft>();
  #listeners = new Set<() => void>();

  get(key: string): Draft | undefined {
    return this.#drafts.get(key);
  }

  all(): Draft[] {
    return [...this.#drafts.values()].sort((a, b) => a.circuit.localeCompare(b.circuit) || a.name.localeCompare(b.name));
  }

  get size(): number {
    return this.#drafts.size;
  }

  save(d: Draft): void {
    this.#drafts.set(d.key, { ...d, updated: Date.now() });
    this.#emit();
  }

  delete(key: string): void {
    if (this.#drafts.delete(key)) this.#emit();
  }

  load(data: unknown, merge = false): void {
    if (!merge) this.#drafts.clear();
    if (Array.isArray(data)) {
      for (const d of data as Draft[]) if (d && typeof d.key === 'string' && Array.isArray(d.fields)) this.#drafts.set(d.key, d);
    }
    this.#emit();
  }

  toJSON(): Draft[] {
    return this.all();
  }

  onChange(listener: () => void): () => void {
    this.#listeners.add(listener);
    return () => this.#listeners.delete(listener);
  }

  /**
   * Definition file with all valid drafts for decoding; drafts that do not
   * parse are left out (the assistant shows their errors).
   */
  definitionFile(): LoadedFile | undefined {
    const valid = this.all().filter((d) => {
      try {
        draftDefinition(d);
        return d.fields.length > 0;
      } catch {
        return false;
      }
    });
    if (!valid.length) return undefined;
    const parsed = parseDefinitionFile(draftsCsv(valid), DRAFTS_PATH, {}, { local: true });
    return { path: DRAFTS_PATH, local: true, parsed, conditionScope: parsed.conditions };
  }

  /** TypeSpec files for the drafts, one per target address and circuit (see draftTspPath). */
  typeSpecFiles(): Map<string, string> {
    const groups = new Map<string, Draft[]>();
    for (const d of this.all()) {
      if (!d.fields.length) continue;
      const path = draftTspPath(d.zz, d.circuit);
      groups.set(path, [...(groups.get(path) ?? []), d]);
    }
    const out = new Map<string, string>();
    for (const [path, drafts] of groups) {
      const defs = drafts.flatMap((d) => {
        try {
          return [draftDefinition(d)];
        } catch {
          return [];
        }
      });
      if (!defs.length) continue;
      const mf = drafts.find((d) => d.manufacturer)?.manufacturer;
      out.set(path, `${TSP_MARKER}\n${writeTypeSpec(defs, mf ? { manufacturer: mf } : {})}`);
    }
    return out;
  }

  #emit(): void {
    for (const l of this.#listeners) l();
  }
}
